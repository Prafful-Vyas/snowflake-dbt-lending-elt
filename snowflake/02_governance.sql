-- Role hierarchy, masking and row access for the LENDING analytics database.

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOADER;        -- Snowpipe / COPY into RAW
CREATE ROLE IF NOT EXISTS TRANSFORMER;   -- dbt: read RAW, own LENDING objects
CREATE ROLE IF NOT EXISTS REPORTER;      -- BI tools: read marts only
CREATE ROLE IF NOT EXISTS CREDIT_RISK;   -- may see unmasked tax identifiers
GRANT ROLE LOADER TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER TO ROLE TRANSFORMER;
GRANT ROLE CREDIT_RISK TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS LENDING;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE WAREHOUSE IF NOT EXISTS REPORTING_WH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA RAW.LENDING TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW.LENDING TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.LENDING TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE LENDING TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE REPORTING_WH TO ROLE REPORTER;

-- Tax identifiers are visible only to credit risk. Everyone else sees the last 3 digits.
CREATE SCHEMA IF NOT EXISTS LENDING.GOVERNANCE;
CREATE MASKING POLICY IF NOT EXISTS LENDING.GOVERNANCE.mask_tax_id AS (val STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('CREDIT_RISK') THEN val
       ELSE REPEAT('*', GREATEST(LENGTH(val) - 3, 0)) || RIGHT(val, 3) END;

-- Relationship managers see only their own region's counterparties.
CREATE TABLE IF NOT EXISTS LENDING.GOVERNANCE.region_entitlements (role_name STRING, country STRING);
CREATE ROW ACCESS POLICY IF NOT EXISTS LENDING.GOVERNANCE.rap_country AS (country STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('CREDIT_RISK') OR IS_ROLE_IN_SESSION('TRANSFORMER')
  OR EXISTS (SELECT 1 FROM LENDING.GOVERNANCE.region_entitlements e
             WHERE IS_ROLE_IN_SESSION(e.role_name) AND e.country = country);

